#!/bin/sh
# End to end: build bc-1.07.1 and flex-2.6.4 twice, once with the reference
# tools (bison -y + flex) and once with lime (lime-yacc + lime-lex), with a
# plain ./configure (no cache overrides), then make, then make check, and
# compare.  For flex, also compare what the two stage1flex binaries (flex
# whose own scan.l went through flex or through lime-lex) generate for every
# corpus scanner.  bc's runtime comparison is bc_e2e_compare.sh.
#   usage: e2e_lex.sh LIME_BUILD_DIR CORPUS_DIR WORK_DIR
# LIME_BUILD_DIR holds the lime binary; limpar.c is copied next to it in
# WORK_DIR/bin, as an installed lime would find it.  Needs: ed (bc's
# fix-libmath_h script), flex, bison, make, cc.
set -u
LB=$1; D=$2; W=$3
H=$(cd "$(dirname "$0")" && pwd)
mkdir -p "$W/bin" || exit 1
cp "$LB/lime" "$W/bin/lime" && cp "$H/../../limpar.c" "$W/bin/limpar.c" || exit 1
ln -sf lime "$W/bin/lime-lex"; ln -sf lime "$W/bin/lime-yacc"
PATH=$W/bin:$PATH; export PATH
for t in ed flex bison make cc; do command -v $t >/dev/null 2>&1 || { echo "SKIP: no $t"; exit 77; }; done
fail=0

build() { # build SRC DIR CONFIGURE-ARGS...
  src=$1; dir=$2; shift 2
  [ -d "$dir" ] && { echo "reuse $dir (delete it to rebuild)"; return 0; }
  mkdir -p "$dir" && cp -a "$src/." "$dir/" || return 1
  # The release tarballs ship pre-generated scanners/parsers: remove them so
  # the tools under test really run.
  for f in bc/bc.c bc/bc.h bc/scan.c src/scan.c; do [ -f "$dir/$f" ] && mv "$dir/$f" "$dir/$f.dist"; done
  ( cd "$dir" && ./configure "$@" > conf.log 2>&1 && make -j4 > make.log 2>&1 && timeout 3000 make -j4 check > check.log 2>&1 )
}

# bc: the drop-in form, bare tool names found through PATH.
build "$D/bc-1.07.1" "$W/bc-ref" YACC='bison -y' LEX=flex || { echo "FAIL bc reference build"; fail=1; }
build "$D/bc-1.07.1" "$W/bc-lime" YACC=lime-yacc LEX=lime-lex || { echo "FAIL bc lime build"; fail=1; }
grep -q 'lime-yacc\|Lime' "$W/bc-lime/bc/bc.c" || { echo "FAIL bc: bc.c not from lime-yacc"; fail=1; }
grep -q 'generated by lime-lex' "$W/bc-lime/bc/scan.c" || { echo "FAIL bc: scan.c not from lime-lex"; fail=1; }
for k in ref lime; do echo "bc-$k: $(grep -h 'checking for flex\|lex library' "$W/bc-$k/conf.log" | tr '\n' ' ')"; done
BC_LIME=$W/bc-lime BC_REF=$W/bc-ref bash "$H/bc_e2e_compare.sh" | tail -n 5

build "$D/flex-2.6.4" "$W/flex-ref" LEX=flex || { echo "FAIL flex reference build/check"; fail=1; }
build "$D/flex-2.6.4" "$W/flex-lime" LEX=lime-lex || { echo "FAIL flex lime build/check"; fail=1; }
grep -q 'generated by lime-lex' "$W/flex-lime/src/scan.c" || { echo "FAIL flex: scan.c not from lime-lex"; fail=1; }
for k in ref lime; do echo "flex-$k make check: $(grep -E '^# (TOTAL|PASS|FAIL|ERROR)' "$W/flex-$k/check.log" | tr '\n' ' ')"; done
same=0; n=0
for f in $(cd "$D" && ls flex-2.6.4/examples/manual/*.lex flex-2.6.4/tests/*.l flex-2.6.4/src/scan.l bison-3.8.2/src/scan-gram.l bc-1.07.1/bc/scan.l postgres-REL_18_0/src/backend/parser/scan.l c11.l 2>/dev/null); do
  n=$((n + 1))
  for k in ref lime; do
    mkdir -p "$W/s1/$k" && ( cd "$W/s1/$k" && find . -type f -delete && timeout 30 "$W/flex-$k/src/stage1flex" "$D/$f" > log 2>&1; echo "rc=$?" >> log )
  done
  if diff -r "$W/s1/ref" "$W/s1/lime" > /dev/null; then same=$((same + 1)); else echo "DIFF stage1flex output: $f"; fail=1; fi
done
echo "stage1flex (scan.l via lime-lex) vs (via flex): $same/$n scanners give identical output"
exit $fail
