/*
** bench_composed_vs_aot_heavy.c -- action-bound A/B benchmark (letter-40/41).
**
** Heavy-reduce-action companion to bench_composed_vs_aot.c: same token
** stream and state-machine shape as the arith bench, but every reduce
** mallocs a tree node + strdup's a label (mimics PG makeNode/pstrdup),
** so parse time is ACTION-bound not dispatch-bound. Contrast the two:
** the composed penalty compresses on this shape (~1.4x) vs arith (~1.6x)
** because the per-reduce allocation is identical on both paths and
** dwarfs the dispatch delta. Result published via %extra_argument is the
** tree NODE COUNT, asserted AOT == composed before timing.
**
** Measures the composed-snapshot push parser (parse_token loop driving
** dynamically-loaded tables, with a bound host_reduce) against the AOT
** generated parser (the compiled-in <Name>() push function calling
** base_yyparse's switch-of-switches) over the SAME token stream, so the
** delta is exactly the push-interpreter penalty letter-39 targets.
**
** The grammar is generated by `lime --host-reduce -n <grammar>.y`, which
** emits three things this bench links against:
**   - <Name>()             : the AOT push parser (path A)
**   - <Name>BuildSnapshot(): a composed snapshot with host_reduce wired
**                            to <Name>HostReduce (path B, host-reduce)
**   - <Name>Alloc/<Name>Free
**
** Both paths compute the same numeric result (asserted equal before
** timing), so this also proves the threaded-dispatch change keeps parse
** RESULTS byte-identical between the two engines.
**
** A third column times the composed path with host_reduce cleared
** (recognition-only) -- the shift-hot-path that must NOT regress from
** the W2 dispatch change relative to a non-composed baseline.
**
** Build (standalone, on the bench box):
**   lime --host-reduce -n bench/bench_arith_grammar.y   # in a tmp dir
**   cc -O2 bench_composed_vs_aot.c bench_arith_grammar.c \
**      bench_arith_grammar_snapshot.c -Iinclude -Isrc \
**      build/src/liblime_parser.a -o bench_composed_vs_aot
*/
#define _POSIX_C_SOURCE 200809L

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <time.h>

#include "parse_context.h"
#include "snapshot.h"

#include "bench_heavy_grammar.h"

/* AOT generated parser API (bench_arith_grammar.c). */
void *HeavyAlloc(void *(*mallocProc)(size_t));
void HeavyFree(void *p, void (*freeProc)(void *));
void Heavy(void *yyp, int yymajor, int yyminor, int *result_out);

/* Composed snapshot builder (bench_arith_grammar_snapshot.c). */
extern ParserSnapshot *HeavyBuildSnapshot(void);

typedef struct { int code; int value; } Tok;

/* ((1+2)*(3+4)-5)/(1+1) = 8 -- 21 tokens incl. the tail. */
static const Tok kExpr[] = {
    { HEAVY_LP, 0 },   { HEAVY_LP, 0 },   { HEAVY_NUM, 1 },  { HEAVY_PLUS, 0 },
    { HEAVY_NUM, 2 },  { HEAVY_RP, 0 },   { HEAVY_STAR, 0 }, { HEAVY_LP, 0 },
    { HEAVY_NUM, 3 },  { HEAVY_PLUS, 0 }, { HEAVY_NUM, 4 },  { HEAVY_RP, 0 },
    { HEAVY_MINUS, 0 },{ HEAVY_NUM, 5 },  { HEAVY_RP, 0 },   { HEAVY_SLASH, 0 },
    { HEAVY_LP, 0 },   { HEAVY_NUM, 1 },  { HEAVY_PLUS, 0 }, { HEAVY_NUM, 1 },
    { HEAVY_RP, 0 },
};
enum { NTOK = (int)(sizeof(kExpr) / sizeof(kExpr[0])) };

static uint64_t now_ns(void) {
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (uint64_t)ts.tv_sec * 1000000000ULL + (uint64_t)ts.tv_nsec;
}

static void *boxi(intptr_t v) { return (void *)v; }

/* --- Path A: AOT generated Heavy() ------------------------------- */
static int aot_parse_once(void) {
    int result = 0;
    void *p = HeavyAlloc(malloc);
    for (int k = 0; k < NTOK; k++) Heavy(p, kExpr[k].code, kExpr[k].value, &result);
    Heavy(p, 0, 0, &result);
    HeavyFree(p, free);
    return result;
}

/* --- Path B: composed snapshot + parse_token, host-reduce --------
** The arith grammar's start action writes the result through its
** %extra_argument {int *result_out}; on the host-reduce path that
** pointer arrives as `user`, so bind a real int* via the session
** override.  parse_result() also returns the start-rule value. */
static intptr_t composed_parse_once(ParserSnapshot *snap) {
    int result_out = 0;
    ParseContext *ctx = parse_begin_borrowed(snap);
    if (ctx == NULL) return -0x7fffffff;
    parse_set_host_reduce(ctx, snap->host_reduce, &result_out);
    for (int k = 0; k < NTOK; k++) {
        (void)parse_token(ctx, kExpr[k].code, boxi(kExpr[k].value), k);
    }
    (void)parse_token(ctx, 0, NULL, -1);
    /* The heavy grammar publishes its answer (tree node count) through the
    ** %extra_argument {int *result_out} -- which arrives as the host_reduce
    ** `user` bound above -- and sets the start value to NULL.  So read the
    ** count from result_out, NOT parse_result() (that would be the NULL
    ** start value).  This mirrors how PostgreSQL reads its parse tree via
    ** the extra-argument, not the start-symbol value. */
    parse_end(ctx);
    return (intptr_t)result_out;
}

/* --- Path C: composed snapshot, recognition-only (no host_reduce) -
** Driven over a snapshot whose host_reduce is NULL, so the engine runs
** the pure shift/reduce/goto dispatch with no reduce callback -- the
** non-composed hot path the W2 threaded-dispatch change must not
** regress. */
static int recog_parse_once(ParserSnapshot *snap) {
    ParseContext *ctx = parse_begin_borrowed(snap);
    if (ctx == NULL) return -1;
    int last = 0;
    for (int k = 0; k < NTOK; k++) {
        last = parse_token(ctx, kExpr[k].code, boxi(kExpr[k].value), k);
    }
    last = parse_token(ctx, 0, NULL, -1);
    parse_end(ctx);
    return last; /* 1 == accepted */
}

static double median_ns_per_parse(uint64_t (*run)(void *, uint32_t), void *arg,
                                   uint32_t iters, int trials) {
    double best[32];
    for (int t = 0; t < trials && t < 32; t++) {
        uint64_t ns = run(arg, iters);
        best[t] = (double)ns / (double)iters;
    }
    /* insertion sort, take median */
    for (int i = 1; i < trials; i++) {
        double v = best[i]; int j = i - 1;
        while (j >= 0 && best[j] > v) { best[j + 1] = best[j]; j--; }
        best[j + 1] = v;
    }
    return best[trials / 2];
}

typedef struct { ParserSnapshot *snap; ParserSnapshot *rsnap; int mode; volatile intptr_t sink; } RunCtx;

static uint64_t run_loop(void *vp, uint32_t iters) {
    RunCtx *c = (RunCtx *)vp;
    uint64_t t0 = now_ns();
    intptr_t acc = 0;
    for (uint32_t i = 0; i < iters; i++) {
        if (c->mode == 0)      acc += aot_parse_once();
        else if (c->mode == 1) acc += composed_parse_once(c->snap);
        else                   acc += recog_parse_once(c->rsnap);
    }
    uint64_t t1 = now_ns();
    c->sink = acc;
    return t1 - t0;
}

int main(int argc, char **argv) {
    uint32_t iters = 200000;
    int trials = 7;
    if (argc > 1) iters = (uint32_t)strtoul(argv[1], NULL, 10);
    if (argc > 2) trials = atoi(argv[2]);

    ParserSnapshot *snap = HeavyBuildSnapshot();
    if (snap == NULL) { fprintf(stderr, "HeavyBuildSnapshot failed\n"); return 1; }

    /* Second snapshot with host_reduce cleared -> recognition-only path. */
    ParserSnapshot *rsnap = HeavyBuildSnapshot();
    if (rsnap == NULL) { fprintf(stderr, "HeavyBuildSnapshot(2) failed\n"); return 1; }
    rsnap->host_reduce = NULL;
    rsnap->host_reduce_user = NULL;

    /* Correctness gate: composed host-reduce result must equal AOT. */
    int aot = aot_parse_once();
    intptr_t comp = composed_parse_once(snap);
    int recog = recog_parse_once(rsnap);
    printf("# tokens/parse=%d  AOT=%d  composed=%ld  recog_accept=%d  host_reduce=%s\n",
           NTOK, aot, (long)comp, recog, snap->host_reduce ? "wired" : "NULL");
    if (snap->host_reduce != NULL && comp != aot) {
        fprintf(stderr, "MISMATCH: composed %ld != AOT %d\n", (long)comp, aot);
        snapshot_release(snap); snapshot_release(rsnap);
        return 2;
    }

    /* warmup */
    RunCtx w = { snap, rsnap, 0, 0 };
    (void)run_loop(&w, 5000);
    w.mode = 1; (void)run_loop(&w, 5000);
    w.mode = 2; (void)run_loop(&w, 5000);

    RunCtx a = { snap, rsnap, 0, 0 }, b = { snap, rsnap, 1, 0 }, c = { snap, rsnap, 2, 0 };
    double aot_ns   = median_ns_per_parse(run_loop, &a, iters, trials);
    double comp_ns  = median_ns_per_parse(run_loop, &b, iters, trials);
    double recog_ns = median_ns_per_parse(run_loop, &c, iters, trials);

    printf("iters=%u trials=%d (median ns/parse)\n", iters, trials);
    printf("  AOT (base_yyparse)        : %8.2f ns\n", aot_ns);
    printf("  composed + host_reduce    : %8.2f ns   ratio %.3fx AOT\n",
           comp_ns, comp_ns / aot_ns);
    printf("  composed recognition-only : %8.2f ns   ratio %.3fx AOT\n",
           recog_ns, recog_ns / aot_ns);

    snapshot_release(snap);
    snapshot_release(rsnap);
    return 0;
}
